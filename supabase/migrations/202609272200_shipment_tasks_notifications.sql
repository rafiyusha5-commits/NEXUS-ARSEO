-- Shipment tasks and in-app notifications (MVP).
--
-- Extends the tables created in 202609270003_phase2_shipments.sql instead of adding new
-- ones:
--   * tasks          — link to a shipment and a stage run, start/completion time,
--                      narrower visibility, writes only through the RPCs below;
--   * notifications  — link to a shipment, new event types, a de-duplication key,
--                      read state changed only through the RPCs below.
-- Events: task assigned / reassigned, deadline approaching, overdue, stage blocked,
-- approval requested, approval decided. Deadline notifications are generated by an
-- idempotent function (on page load for the current user and by a scheduled job).
-- Every task change keeps going through the existing audit_task trigger (audit_log).
--
-- Idempotent: columns, indexes, constraints, policies and functions are re-created.
-- Apply after 202609272000_product_catalog_classification.sql.

-- 1. Permission for task managers ---------------------------------------------------------

insert into public.permissions (code, module, action, name, description) values
  ('tasks.manage', 'tasks', 'manage', 'Задачи: управление',
   'Просмотр задач сотрудников, назначение другим, переназначение, изменение срока, отмена и возобновление')
on conflict (code) do update set name = excluded.name, description = excluded.description;

insert into public.role_permissions (role_id, permission_id, granted)
select r.id, p.id, true
from public.app_roles r
join public.permissions p on p.code = 'tasks.manage'
where r.code in ('administrator', 'director', 'executive_director', 'logistics_director', 'senior_logistics_manager')
on conflict (role_id, permission_id) do nothing;

