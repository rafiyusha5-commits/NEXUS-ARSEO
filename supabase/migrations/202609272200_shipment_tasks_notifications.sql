-- A stage run fixes the shipment; generic entity columns follow the links when empty.
create or replace function private.prepare_task()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_run_shipment uuid;
begin
  if new.stage_run_id is not null then
    select shipment_id into v_run_shipment from public.shipment_stage_runs where id = new.stage_run_id;
    if v_run_shipment is null then
      raise exception 'Этап поставки не найден';
    end if;
    if new.shipment_id is not null and new.shipment_id <> v_run_shipment then
      raise exception 'Этап относится к другой поставке';
    end if;
    new.shipment_id := v_run_shipment;
  end if;
  if new.entity_type is null and new.entity_id is null then
    if new.stage_run_id is not null then
      new.entity_type := 'shipment_stage_run';
      new.entity_id := new.stage_run_id;
    elsif new.shipment_id is not null then
      new.entity_type := 'shipment';
      new.entity_id := new.shipment_id;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists prepare_task on public.tasks;
create trigger prepare_task
  before insert or update of shipment_id, stage_run_id on public.tasks
  for each row execute function private.prepare_task();

-- Who sees a task: an employee holding tasks.view (so a personal deny override closes the
-- section completely) who is its assignee or creator, a task manager, or the employee
-- responsible for the linked shipment. tasks.view alone does not show other people's tasks.
drop policy if exists "users view relevant tasks" on public.tasks;
create policy "users view relevant tasks" on public.tasks for select to authenticated
using (
  (select private.has_permission('tasks.view'))
  and (
    assignee_user_id = (select auth.uid())
    or created_by = (select auth.uid())
    or (select private.has_permission('tasks.manage'))
    or (shipment_id is not null and exists (
      select 1 from public.shipments s
      where s.id = shipment_id and s.responsible_user_id = (select auth.uid())
    ))
  )
);

-- Tasks change only through the RPCs, which enforce who may do what.
drop policy if exists "users create tasks" on public.tasks;
drop policy if exists "users update tasks" on public.tasks;
revoke insert, update, delete on public.tasks from anon, authenticated;

-- 3. Notifications ----------------------------------------------------------------------

alter table public.notifications
  add column if not exists shipment_id uuid references public.shipments(id) on delete cascade,
  add column if not exists dedupe_key text;

alter table public.notifications drop constraint if exists notifications_type_check;
alter table public.notifications add constraint notifications_type_check check (type in (
  'deadline', 'overdue', 'approval_request', 'approval_decision', 'status_change', 'discrepancy',
  'low_shelf_life', 'document_uploaded', 'sync_error', 'system',
  'task_assigned', 'task_reassigned', 'stage_blocked'));

-- The same event is stored once per recipient, however often it is generated.
create unique index if not exists notifications_dedupe_key_unique
  on public.notifications (recipient_user_id, dedupe_key) where dedupe_key is not null;
create index if not exists notifications_recipient_created_idx
  on public.notifications (recipient_user_id, created_at desc);
-- Keeps the unread counter in the sidebar an index-only lookup.
create index if not exists notifications_unread_idx
  on public.notifications (recipient_user_id) where not is_read;

-- Recipients read their own notifications. Task notifications (entity_type = 'task') carry
-- task titles and dates, so they follow tasks.view like the tasks themselves: a personal
-- deny hides even notifications created before it. Approvals, documents and shipment
-- stages stay visible. The unread counter and notification_deliveries go through this
-- policy as well.
drop policy if exists "users view own notifications" on public.notifications;
create policy "users view own notifications" on public.notifications for select to authenticated
using (
  recipient_user_id = (select auth.uid())
  and (entity_type is distinct from 'task' or (select private.has_permission('tasks.view')))
);

-- Notifications are created by database functions and read state changes through RPCs.
drop policy if exists "users update own notifications" on public.notifications;
revoke insert, update, delete on public.notifications from anon, authenticated;
revoke insert, update, delete on public.notification_deliveries from anon, authenticated;

-- 4. Helpers -----------------------------------------------------------------------------

create or replace function private.is_active_employee(p_user uuid)
returns boolean
language sql
security definer
set search_path = ''
stable
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = p_user and p.is_active and p.user_type = 'employee'
  );
$$;

-- private.has_permission() for another user; used only to pick notification recipients.
create or replace function private.user_has_permission(p_user uuid, p_permission text)
returns boolean
language sql
security definer
set search_path = ''
stable
as $$
  select
    private.is_active_employee(p_user)
    and not exists (
      select 1
      from public.user_permission_overrides o
      join public.permissions p on p.id = o.permission_id
      where o.user_id = p_user and p.code = p_permission and o.effect = 'deny'
        and o.revoked_at is null and (o.expires_at is null or o.expires_at > now())
    )
    and (
      exists (
        select 1
        from public.user_permission_overrides o
        join public.permissions p on p.id = o.permission_id
        where o.user_id = p_user and p.code = p_permission and o.effect = 'allow'
          and o.revoked_at is null and (o.expires_at is null or o.expires_at > now())
      )
      or exists (
        select 1
        from public.user_roles ur
        join public.app_roles r on r.id = ur.role_id
        join public.role_permissions rp on rp.role_id = r.id
        join public.permissions p on p.id = rp.permission_id
        where ur.user_id = p_user and r.is_enabled and rp.granted and p.code = p_permission
          and (ur.expires_at is null or ur.expires_at > now())
      )
    );
$$;

-- Local time of ARSEO (Kazakhstan, UTC+5) for notification texts.
create or replace function private.format_local_time(p_value timestamptz)
returns text
language sql
stable
set search_path = ''
as $$
  select to_char(p_value at time zone 'Asia/Qyzylorda', 'DD.MM.YYYY HH24:MI');
$$;

-- Inserts one notification unless the recipient is not an active employee, the same
-- de-duplication key was already used for them, or it is about a task and the recipient
-- lacks tasks.view. Returns true when a row was inserted.
create or replace function private.notify(
  p_recipient uuid, p_type text, p_title text, p_body text,
  p_entity_type text, p_entity_id uuid, p_shipment_id uuid, p_dedupe_key text default null)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_recipient is null or not private.is_active_employee(p_recipient) then
    return false;
  end if;
  if p_entity_type = 'task' and not private.user_has_permission(p_recipient, 'tasks.view') then
    return false;
  end if;
  insert into public.notifications (recipient_user_id, type, title, body, entity_type, entity_id, shipment_id, dedupe_key)
  values (p_recipient, p_type, left(p_title, 200), left(p_body, 1000), p_entity_type, p_entity_id, p_shipment_id, p_dedupe_key)
  on conflict (recipient_user_id, dedupe_key) where dedupe_key is not null do nothing;
  return found;
end;
$$;

create or replace function private.task_context(p_task public.tasks)
returns text
language sql
security definer
set search_path = ''
stable
as $$
  select concat_ws(' · ',
    (select s.shipment_number from public.shipments s where s.id = p_task.shipment_id),
    (select st.name ->> 'ru' from public.shipment_stage_runs r join public.shipment_stages st on st.id = r.stage_id
     where r.id = p_task.stage_run_id),
    case when p_task.due_at is not null then 'срок ' || private.format_local_time(p_task.due_at) end);
$$;

-- 5. Event triggers ----------------------------------------------------------------------

create or replace function private.notify_task_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_actor_name text;
  v_new_name text;
  v_context text := private.task_context(new);
begin
  select full_name into v_actor_name from public.profiles where id = coalesce(v_actor, new.created_by);
  if tg_op = 'INSERT' then
    if new.assignee_user_id is distinct from coalesce(v_actor, new.created_by) then
      perform private.notify(new.assignee_user_id, 'task_assigned', 'Новая задача: ' || new.title,
        concat_ws('. ', 'Назначил(а): ' || coalesce(v_actor_name, 'система'), nullif(v_context, '')),
        'task', new.id, new.shipment_id, 'task_assigned:' || new.id);
    end if;
  elsif new.assignee_user_id is distinct from old.assignee_user_id then
    select full_name into v_new_name from public.profiles where id = new.assignee_user_id;
    if new.assignee_user_id is distinct from v_actor then
      perform private.notify(new.assignee_user_id, 'task_reassigned', 'Вам передана задача: ' || new.title,
        concat_ws('. ', 'Передал(а): ' || coalesce(v_actor_name, 'система'), nullif(v_context, '')),
        'task', new.id, new.shipment_id, null);
    end if;
    if old.assignee_user_id is distinct from v_actor then
      perform private.notify(old.assignee_user_id, 'task_reassigned', 'Задача передана другому исполнителю: ' || new.title,
        'Новый исполнитель: ' || coalesce(v_new_name, '—'), 'task', new.id, new.shipment_id, null);
    end if;
  end if;
  return null;
end;
$$;

drop trigger if exists notify_task_change on public.tasks;
create trigger notify_task_change
  after insert or update of assignee_user_id on public.tasks
  for each row execute function private.notify_task_change();

-- A blocked stage is reported to the shipment owner, the stage owner and the assignees
-- of open tasks of that stage (not to the employee who blocked it).
create or replace function private.notify_stage_blocked()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_shipment public.shipments%rowtype;
  v_stage_name text;
  v_recipient uuid;
begin
  if new.status <> 'blocked' or old.status = 'blocked' then
    return null;
  end if;
  select * into v_shipment from public.shipments where id = new.shipment_id;
  select name ->> 'ru' into v_stage_name from public.shipment_stages where id = new.stage_id;
  for v_recipient in
    select distinct u from (
      select v_shipment.responsible_user_id as u
      union all select new.responsible_user_id
      union all select t.assignee_user_id from public.tasks t
        where t.stage_run_id = new.id and t.status in ('open', 'in_progress')
    ) recipients
    where u is not null and u is distinct from v_actor
  loop
    perform private.notify(v_recipient, 'stage_blocked',
      'Этап заблокирован: ' || coalesce(v_stage_name, 'этап поставки'),
      concat_ws('. ', 'Поставка ' || v_shipment.shipment_number, 'Причина: ' || coalesce(new.status_reason, 'не указана')),
      'shipment_stage_run', new.id, new.shipment_id, null);
  end loop;
  return null;
end;
$$;

drop trigger if exists notify_stage_blocked on public.shipment_stage_runs;
create trigger notify_stage_blocked
  after update of status on public.shipment_stage_runs
  for each row execute function private.notify_stage_blocked();

-- Subject of an approval for notification texts and links.
create or replace function private.approval_subject(p_entity_type text, p_entity_id uuid, out label text, out shipment_id uuid)
language plpgsql
security definer
set search_path = ''
stable
as $$
begin
  if p_entity_type = 'shipment' then
    select 'поставка ' || s.shipment_number, s.id into label, shipment_id from public.shipments s where s.id = p_entity_id;
  elsif p_entity_type = 'document' then
    select 'документ «' || d.title || '»' into label from public.documents d where d.id = p_entity_id;
  end if;
  label := coalesce(label, 'запрос на согласование');
end;
$$;

-- Request: the named approver, or every active employee holding the approver role
-- (a role code) or permission (a code with a dot, e.g. documents.approve).
-- Decision: the employee who requested it.
create or replace function private.notify_approval_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_subject record;
  v_requester text;
  v_recipient uuid;
begin
  select * into v_subject from private.approval_subject(new.entity_type, new.entity_id);
  if tg_op = 'INSERT' and new.status = 'pending' then
    select full_name into v_requester from public.profiles where id = new.requested_by;
    for v_recipient in
      select new.approver_user_id where new.approver_user_id is not null
      union
      select p.id from public.profiles p
      where new.approver_user_id is null and new.approver_role is not null
        and p.is_active and p.user_type = 'employee'
        and case
          when position('.' in new.approver_role) > 0 then private.user_has_permission(p.id, new.approver_role)
          else exists (
            select 1 from public.user_roles ur join public.app_roles r on r.id = ur.role_id
            where ur.user_id = p.id and r.code = new.approver_role and r.is_enabled
              and (ur.expires_at is null or ur.expires_at > now()))
        end
    loop
      if v_recipient is distinct from new.requested_by then
        perform private.notify(v_recipient, 'approval_request', 'Запрос на согласование: ' || v_subject.label,
          concat_ws('. ', 'Запросил(а): ' || coalesce(v_requester, '—'), nullif(btrim(coalesce(new.request_comment, '')), '')),
          new.entity_type, new.entity_id, v_subject.shipment_id, 'approval_request:' || new.id);
      end if;
    end loop;
  elsif tg_op = 'UPDATE' and old.status = 'pending' and new.status in ('approved', 'rejected')
        and new.requested_by is distinct from v_actor then
    perform private.notify(new.requested_by, 'approval_decision',
      'Согласование завершено: ' || v_subject.label || case when new.status = 'approved' then ' — утверждено' else ' — отклонено' end,
      nullif(btrim(coalesce(new.comment, '')), ''),
      new.entity_type, new.entity_id, v_subject.shipment_id, 'approval_decision:' || new.id);
  end if;
  return null;
end;
$$;

drop trigger if exists notify_approval_change on public.approvals;
create trigger notify_approval_change
  after insert or update of status on public.approvals
  for each row execute function private.notify_approval_change();

-- 6. Deadline notifications ------------------------------------------------------------

-- Approaching (within p_window) and overdue open tasks. The key contains the due date, so
-- a repeated run adds nothing, while a new due date is reported again. Overdue tasks are
-- also reported to their creator. p_user limits the run to notifications for one user.
-- Recipients without tasks.view get nothing.
create or replace function private.generate_deadline_notifications(
  p_user uuid, p_now timestamptz, p_window interval default interval '24 hours')
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  insert into public.notifications (recipient_user_id, type, title, body, entity_type, entity_id, shipment_id, dedupe_key)
  select c.recipient, c.kind, left(c.title, 200), c.body, 'task', c.id, c.shipment_id,
         'task_' || c.kind || ':' || c.id || ':' || extract(epoch from c.due_at)::bigint
  from (
    select t.id, t.shipment_id, t.due_at, t.assignee_user_id as recipient,
           case when t.due_at <= p_now then 'overdue' else 'deadline' end as kind,
           case when t.due_at <= p_now then 'Задача просрочена: ' else 'Срок задачи истекает: ' end || t.title as title,
           concat_ws('. ', case when t.due_at <= p_now then 'Срок был ' else 'Срок ' end || private.format_local_time(t.due_at),
             nullif(private.task_context(t), '')) as body
    from public.tasks t
    where t.status in ('open', 'in_progress') and t.due_at is not null and t.due_at <= p_now + p_window
    union all
    select t.id, t.shipment_id, t.due_at, t.created_by, 'overdue',
           'Просрочена задача сотрудника ' || coalesce(p.full_name, '—') || ': ' || t.title,
           'Срок был ' || private.format_local_time(t.due_at)
    from public.tasks t
    left join public.profiles p on p.id = t.assignee_user_id
    where t.status in ('open', 'in_progress') and t.due_at is not null and t.due_at <= p_now
      and t.created_by is not null and t.created_by <> t.assignee_user_id
  ) c
  -- user_has_permission() also requires an active employee.
  where (p_user is null or c.recipient = p_user) and private.user_has_permission(c.recipient, 'tasks.view')
  on conflict (recipient_user_id, dedupe_key) where dedupe_key is not null do nothing;
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

-- Called by the task and notification pages for the signed-in employee.
create or replace function public.refresh_my_deadline_notifications()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not (select private.has_permission('tasks.view')) then
    raise exception 'Нет доступа к задачам' using errcode = '42501';
  end if;
  return private.generate_deadline_notifications((select auth.uid()), now());
end;
$$;

-- For a scheduled job (pg_cron in the database or a server job with the secret key).
create or replace function public.generate_deadline_notifications(p_now timestamptz default now())
returns integer
language sql
security definer
set search_path = ''
as $$
  select private.generate_deadline_notifications(null, p_now);
$$;

-- 7. Task RPCs -------------------------------------------------------------------------

create or replace function public.create_task(
  p_title text,
  p_assignee_user_id uuid,
  p_due_at timestamptz default null,
  p_priority text default 'normal',
  p_description text default null,
  p_shipment_id uuid default null,
  p_stage_run_id uuid default null)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_title text := btrim(coalesce(p_title, ''));
  v_id uuid;
begin
  if not (select private.has_permission('tasks.create')) then
    raise exception 'Недостаточно прав для создания задачи' using errcode = '42501';
  end if;
  if length(v_title) = 0 or length(v_title) > 200 then
    raise exception 'Название задачи — от 1 до 200 символов';
  end if;
  if p_description is not null and length(p_description) > 2000 then
    raise exception 'Описание не должно превышать 2000 символов';
  end if;
  if coalesce(p_priority, 'normal') not in ('low', 'normal', 'high', 'urgent') then
    raise exception 'Недопустимый приоритет';
  end if;
  if not private.is_active_employee(p_assignee_user_id) then
    raise exception 'Исполнитель не найден или неактивен';
  end if;
  if p_assignee_user_id <> v_actor and not (select private.has_permission('tasks.manage')) then
    raise exception 'Назначать задачи другим сотрудникам может только руководитель' using errcode = '42501';
  end if;
  if p_due_at is not null and p_due_at < now() - interval '1 minute' then
    raise exception 'Срок не может быть в прошлом';
  end if;
  if (p_shipment_id is not null or p_stage_run_id is not null) and not (select private.has_permission('shipments.view')) then
    raise exception 'Нет доступа к поставкам' using errcode = '42501';
  end if;
  if p_shipment_id is not null and not exists (select 1 from public.shipments where id = p_shipment_id) then
    raise exception 'Поставка не найдена';
  end if;

  insert into public.tasks (title, description, assignee_user_id, created_by, priority, due_at, status, shipment_id, stage_run_id)
  values (v_title, nullif(btrim(coalesce(p_description, '')), ''), p_assignee_user_id, v_actor,
          coalesce(p_priority, 'normal'), p_due_at, 'open', p_shipment_id, p_stage_run_id)
  returning id into v_id;
  return v_id;
end;
$$;

-- Status rules (mirrored in src/lib/tasks/rules.ts):
--   assignee: open → in_progress, open/in_progress → done, in_progress → open;
--   manager (tasks.manage) or creator: open/in_progress → cancelled;
--   manager: done/cancelled → open.
create or replace function public.set_task_status(p_task_id uuid, p_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_task public.tasks%rowtype;
  v_manager boolean := (select private.has_permission('tasks.manage'));
  v_assignee boolean;
begin
  if not (select private.has_permission('tasks.view')) then
    raise exception 'Нет доступа к задачам' using errcode = '42501';
  end if;
  select * into v_task from public.tasks where id = p_task_id for update;
  if not found then
    raise exception 'Задача не найдена';
  end if;
  v_assignee := v_task.assignee_user_id = v_actor;
  if not (
    (v_assignee and v_task.status = 'open' and p_status = 'in_progress')
    or (v_assignee and v_task.status in ('open', 'in_progress') and p_status = 'done')
    or (v_assignee and v_task.status = 'in_progress' and p_status = 'open')
    or ((v_manager or v_task.created_by = v_actor) and v_task.status in ('open', 'in_progress') and p_status = 'cancelled')
    or (v_manager and v_task.status in ('done', 'cancelled') and p_status = 'open')
  ) then
    raise exception 'Нельзя перевести задачу из статуса «%» в «%»', v_task.status, p_status using errcode = '42501';
  end if;
  update public.tasks set
    status = p_status,
    started_at = case when p_status = 'in_progress' then coalesce(started_at, now()) else started_at end,
    completed_at = case when p_status in ('done', 'cancelled') then now() else null end,
    updated_at = now()
  where id = p_task_id;
end;
$$;

create or replace function public.reassign_task(p_task_id uuid, p_assignee_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_task public.tasks%rowtype;
begin
  if not ((select private.has_permission('tasks.view')) and (select private.has_permission('tasks.manage'))) then
    raise exception 'Переназначать задачи может только руководитель' using errcode = '42501';
  end if;
  select * into v_task from public.tasks where id = p_task_id for update;
  if not found then
    raise exception 'Задача не найдена';
  end if;
  if v_task.status not in ('open', 'in_progress') then
    raise exception 'Завершённую или отменённую задачу нельзя переназначить';
  end if;
  if not private.is_active_employee(p_assignee_user_id) then
    raise exception 'Исполнитель не найден или неактивен';
  end if;
  if v_task.assignee_user_id = p_assignee_user_id then
    raise exception 'Задача уже назначена этому сотруднику';
  end if;
  -- The new assignee starts from scratch.
  update public.tasks set assignee_user_id = p_assignee_user_id, status = 'open', started_at = null, updated_at = now()
  where id = p_task_id;
end;
$$;

create or replace function public.change_task_due(p_task_id uuid, p_due_at timestamptz)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_task public.tasks%rowtype;
begin
  if not ((select private.has_permission('tasks.view')) and (select private.has_permission('tasks.manage'))) then
    raise exception 'Менять срок задачи может только руководитель' using errcode = '42501';
  end if;
  select * into v_task from public.tasks where id = p_task_id for update;
  if not found then
    raise exception 'Задача не найдена';
  end if;
  if v_task.status not in ('open', 'in_progress') then
    raise exception 'Срок завершённой или отменённой задачи не меняется';
  end if;
  if p_due_at is not null and p_due_at < now() - interval '1 minute' then
    raise exception 'Срок не может быть в прошлом';
  end if;
  if v_task.due_at is not distinct from p_due_at then
    raise exception 'Срок не изменился';
  end if;
  update public.tasks set due_at = p_due_at, updated_at = now() where id = p_task_id;
end;
$$;

-- 8. Notification RPCs -----------------------------------------------------------------

create or replace function public.mark_notification_read(p_notification_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- Same visibility as the read policy: hidden task notifications are not touched.
  update public.notifications set is_read = true, read_at = coalesce(read_at, now())
  where id = p_notification_id and recipient_user_id = (select auth.uid())
    and (entity_type is distinct from 'task' or (select private.has_permission('tasks.view')));
  if not found then
    raise exception 'Уведомление не найдено';
  end if;
end;
$$;

create or replace function public.mark_all_notifications_read()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  if (select auth.uid()) is null then
    raise exception 'Требуется авторизация' using errcode = '42501';
  end if;
  update public.notifications set is_read = true, read_at = now()
  where recipient_user_id = (select auth.uid()) and not is_read
    and (entity_type is distinct from 'task' or (select private.has_permission('tasks.view')));
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

